#!/usr/bin/env python3
"""Generates src/Hearthlens.Core/Battlegrounds/Effects/ongoing/UndeadPool.g.cs.

Deathly Striker (BG31_835): "Avenge (4): Get a random Undead. Deathrattle: Summon it from your hand for this combat
only." (golden: 2). The simulator needs the public list of Undead it can get. This script takes them from the research
card data of the current patch:

  every Battlegrounds pool minion (IS_BACON_POOL_MINION) whose types include UNDEAD or ALL,
  except Dark Paradox (its type, stats and tier change every game) and the Duos-only minions,

with its printed (normal) Attack, Health, tribes, keywords, mechanics and tier.

Usage (isolated interpreter, data file passed as an argument):
  python3 -I tools/effects/gen_undead_pool.py <bg_pool_effects.json> <output.g.cs>
"""
import json
import re
import sys

EXCLUDED = {"BG36_360"}  # Dark Paradox

TRIBES = {
    "BEAST": "Tribe.Beast",
    "DEMON": "Tribe.Demon",
    "DRAGON": "Tribe.Dragon",
    "ELEMENTAL": "Tribe.Elemental",
    "MECHANICAL": "Tribe.Mech",
    "MURLOC": "Tribe.Murloc",
    "NAGA": "Tribe.Naga",
    "PIRATE": "Tribe.Pirate",
    "QUILBOAR": "Tribe.Quilboar",
    "UNDEAD": "Tribe.Undead",
    "ABERRATION": "Tribe.Aberration",
    "ALL": "Tribe.All",
}

KEYWORDS = {
    "TAUNT": "Keyword.Taunt",
    "DIVINE_SHIELD": "Keyword.DivineShield",
    "POISONOUS": "Keyword.Poisonous",
    "VENOMOUS": "Keyword.Venomous",
    "REBORN": "Keyword.Reborn",
    "WINDFURY": "Keyword.Windfury",
    "MEGA_WINDFURY": "Keyword.MegaWindfury",
    "STEALTH": "Keyword.Stealth",
}

MECHANICS = {
    "DEATHRATTLE": "CardMechanic.Deathrattle",
    "BACON_RALLY": "CardMechanic.Rally",
    "AVENGE": "CardMechanic.Avenge",
    "BATTLECRY": "CardMechanic.Battlecry",
    "START_OF_COMBAT": "CardMechanic.StartOfCombat",
    "MAGNETIC": "CardMechanic.Magnetic",
}


def flags(values, table, none):
    parts = [table[v] for v in values if v in table]
    return " | ".join(parts) if parts else none


def main(source, target):
    with open(source, encoding="utf-8") as f:
        data = json.load(f)

    patch = data.get("build", {}).get("CardDefs.Bacon.xml", "")
    rows = []
    for m in data["minions"]:
        tribes = [t for t in (m.get("tribes") or "").split("|") if t]
        if m["id"] in EXCLUDED or m.get("duos_only") == "y":
            continue
        if "UNDEAD" not in tribes and "ALL" not in tribes:
            continue
        rows.append((int(m["tier"]), m["id"], m))

    rows.sort(key=lambda r: (r[0], r[1]))
    lines = []
    for tier, card_id, m in rows:
        tribes = [t for t in (m.get("tribes") or "").split("|") if t]
        mechanics = [x for x in (m.get("mechanics") or "").split("|") if x]
        name = re.sub(r"[\r\n]", " ", m["name"])
        lines.append(
            f'        M("{card_id}", {int(m["atk"] or 0)}, {int(m["health"] or 0)}, {tier}, '
            f'{flags(tribes, TRIBES, "Tribe.None")}, {flags(mechanics, KEYWORDS, "Keyword.None")}, '
            f'{flags(mechanics, MECHANICS, "CardMechanic.None")}), // {name}'
        )

    body = "\n".join(lines)
    text = f"""// <auto-generated>
// Generated by tools/effects/gen_undead_pool.py from the research card data (bg_pool_effects.json,
// patch 37.0.0.{patch}). Do not edit by hand: regenerate after a patch.
// </auto-generated>
namespace Hearthlens.Core.Battlegrounds.Effects.Ongoing;

internal static partial class UndeadPool
{{
    public const string Patch = "37.0.0.{patch}";

    /// <summary>Undead (and all-type) pool minions, not Duos-only, by tier then card id: printed normal stats.</summary>
    private static readonly SimMinion[] Generated =
    [
{body}
    ];
}}
"""
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"{len(rows)} minions -> {target}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
