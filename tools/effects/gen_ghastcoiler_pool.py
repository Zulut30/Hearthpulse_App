#!/usr/bin/env python3
"""Generates src/Hearthlens.Core/Battlegrounds/Effects/deaths/GhastcoilerPool.g.cs.

Ghastcoiler (BGS_008): "Deathrattle: Summon 2 random Deathrattle minions." (golden: 4). The simulator needs the
public list of minions it can summon. This script takes them from the research card data of the current patch:

  every Battlegrounds pool minion (IS_BACON_POOL_MINION) whose mechanics include DEATHRATTLE,
  except Ghastcoiler itself and the Duos-only minions,

with its printed (normal) Attack, Health, tribes, keywords and tier.

Usage (isolated interpreter, data file passed as an argument):
  python3 -I tools/effects/gen_ghastcoiler_pool.py <bg_pool_effects.json> <output.g.cs>
"""
import json
import re
import sys

GHASTCOILER = "BGS_008"

TRIBES = {
    "BEAST": "Tribe.Beast",
    "DEMON": "Tribe.Demon",
    "DRAGON": "Tribe.Dragon",
    "ELEMENTAL": "Tribe.Elemental",
    "MECHANICAL": "Tribe.Mech",
    "MURLOC": "Tribe.Murloc",
    "NAGA": "Tribe.Naga",
    "PIRATE": "Tribe.Pirate",
    "QUILBOAR": "Tribe.Quilboar",
    "UNDEAD": "Tribe.Undead",
    "ABERRATION": "Tribe.Aberration",
    "ALL": "Tribe.All",
}

KEYWORDS = {
    "TAUNT": "Keyword.Taunt",
    "DIVINE_SHIELD": "Keyword.DivineShield",
    "POISONOUS": "Keyword.Poisonous",
    "VENOMOUS": "Keyword.Venomous",
    "REBORN": "Keyword.Reborn",
    "WINDFURY": "Keyword.Windfury",
    "MEGA_WINDFURY": "Keyword.MegaWindfury",
    "STEALTH": "Keyword.Stealth",
}

MECHANICS = {
    "DEATHRATTLE": "CardMechanic.Deathrattle",
    "BACON_RALLY": "CardMechanic.Rally",
    "AVENGE": "CardMechanic.Avenge",
    "BATTLECRY": "CardMechanic.Battlecry",
    "START_OF_COMBAT": "CardMechanic.StartOfCombat",
    "MAGNETIC": "CardMechanic.Magnetic",
}


def flags(values, table, none):
    parts = [table[v] for v in values if v in table]
    return " | ".join(parts) if parts else none


def main(source, output):
    with open(source, encoding="utf-8") as f:
        data = json.load(f)

    build = data.get("build", {})
    found = re.search(r"patch ([\d.]+)", data.get("source", ""))
    patch = found.group(1) if found else build.get("CardDefs.Bacon.xml") or next(iter(build.values()), "")

    rows = []
    for m in data["minions"]:
        mechanics = [x for x in (m.get("mechanics") or "").split("|") if x]
        if "DEATHRATTLE" not in mechanics or m["id"] == GHASTCOILER or str(m.get("duos_only")).lower() == "y":
            continue
        tribes = [t for t in (m.get("tribes") or "").split("|") if t]
        rows.append((int(m["tier"]), m["id"], m["name"], int(m["atk"] or 0), int(m["health"] or 0),
                     flags(tribes, TRIBES, "Tribe.None"), flags(mechanics, KEYWORDS, "Keyword.None"),
                     flags(mechanics, MECHANICS, "CardMechanic.None")))
    rows.sort()

    lines = [
        "// <auto-generated>",
        "// Generated by tools/effects/gen_ghastcoiler_pool.py from the research card data (bg_pool_effects.json,",
        f"// patch {patch}). Do not edit by hand: regenerate after a patch.",
        "// </auto-generated>",
        "namespace Hearthlens.Core.Battlegrounds.Effects.Deaths;",
        "",
        "internal static partial class GhastcoilerPool",
        "{",
        f"    public const string Patch = \"{patch}\";",
        "",
        "    /// <summary>Pool minions with a Deathrattle (not Ghastcoiler, not Duos-only), by tier then card id: printed normal stats.</summary>",
        "    private static readonly SimMinion[] Generated =",
        "    [",
    ]
    for tier, card_id, name, atk, hp, tribe, keywords, mechanics in rows:
        lines.append(f"        M(\"{card_id}\", {atk}, {hp}, {tier}, {tribe}, {keywords}, {mechanics}), // {name}")
    lines += ["    ];", "}", ""]

    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(rows)} minions -> {output}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
