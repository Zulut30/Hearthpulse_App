#!/usr/bin/env python3
"""Generates src/Hearthpulse.Core/CardPool/CardPoolTables.g.cs.

The card pool panel (src/Hearthpulse.Core/CardPool) reads a generator's English text to find the pool it draws from.
Collectible cards bring their English text with the card catalog (Hearthpulse API); this script adds what the catalog
cannot give:

- GeneratorTexts: English text of non-collectible Constructed cards that Discover or create random cards (hero
  powers, tokens, Dark Gifts, quest rewards...), so a choice they open can be explained in any client language;
- Overrides: the exception table - generators whose text the parser must not read literally (a pool that depends on
  the game state, a named group of cards), keyed by every card id that carries the text;
- StandardSets: sets in Standard, used only when the API is down and the HearthstoneJSON fallback has no formats.

Input: HearthstoneJSON cards.json in English (https://api.hearthstonejson.com/v1/latest/enUS/cards.json).

Usage (isolated interpreter, data file passed as an argument):
  python3 -I tools/cardpool/gen_pool_tables.py cards.enUS.json src/Hearthpulse.Core/CardPool/CardPoolTables.g.cs

Regenerate after a patch; update STANDARD_SETS at rotation (card_set values of
https://api.kolodahearthstone.com/api/v1/constructed-cards?format=standard).
"""
import json
import re
import sys

STANDARD_SETS = [
    "CORE", "EVENT", "EMERALD_DREAM", "THE_LOST_CITY", "TIME_TRAVEL", "CATACLYSM", "ESCAPEFROM_VIOLET_HOLD", "BE",
]

# Sets whose cards never show up in Constructed games.
EXCLUDED_SETS = {"BATTLEGROUNDS", "LETTUCE", "TB", "CREDITS", "HERO_SKINS", "MISSIONS", "TUTORIAL", "PLACEHOLDER_202204"}

TYPES = {"SPELL", "MINION", "HERO_POWER", "WEAPON", "LOCATION", "HERO"}

GENERATOR = re.compile(r"Discover|\brandom\b")

# Exception table: (regex over the normalised English text, action). Actions:
#   ("skip", reason)      - generates, but not from a pool the catalog can answer;
#   ("text", english)     - parse this text instead of the card's own;
#   ("sub", regex, repl)  - parse the card's own text with regex replaced by repl;
#   ("cards", [names])    - an explicit pool of collectible cards, by English name.
# Keep reasons short: they go to hearthpulse.log when such a card is played.
OVERRIDES = [
    (r"with Cost equal to|of that Cost|that costs that much|\{0\}-Cost|playable spell|a type you haven't played",
     ("skip", "the pool depends on the game state")),
    (r"random (?:minion|spell|card) of the same (?:Cost|Rarity)|Discover a card of the same Rarity",
     ("skip", "the pool depends on another card")),
    (r"Rune card|Blood, Frost or Unholy card", ("skip", "rune costs are not in the card catalog")),
    (r"Animal Companion|Beast Companion|Dormant Dreadseed|Dream card|random Leyline|Shatter card|random Mask\b"
     r"|Rewind card|Wild God|Fel Beast|Paladin Aura|contraband|random Old God|the perfect tech card",
     ("skip", "a named group of cards that the catalog does not mark")),
    (r"random 2-Cost minion that is Dormant for 2 turns", ("sub", r" that is Dormant for 2 turns", "")),
    (r"into random Druid ones", ("sub", r"random Druid ones", "random Druid cards")),
    (r"Fire spells at random enemies", ("text", "Cast random Fire spells.")),
]
HEADER = """// <auto-generated>
// Generated by tools/cardpool/gen_pool_tables.py from HearthstoneJSON (enUS). Do not edit by hand.
// </auto-generated>
#nullable enable

namespace Hearthpulse.Core.CardPool;

internal static class CardPoolTables
{
"""


def normalize(text):
    """Mirrors PoolText.Normalize in C#."""
    if not text:
        return ""
    t = re.sub(r"<[^>]*>", "", text)
    t = re.sub(r"\|4\(([^,)]*),([^)]*)\)", r"\2", t)
    t = t.replace("[x]", "")
    for ch in "$#@&":
        t = t.replace(ch, " ")
    t = t.replace(" ", " ").replace("\n", " ").replace("\r", " ").replace("’", "'")
    t = re.sub(r"\s+", " ", t).strip()
    return t.replace(" .", ".").replace(" ,", ",").replace(" :", ":")


def cs(value):
    return json.dumps(value, ensure_ascii=False)


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)

    with open(sys.argv[1], encoding="utf-8") as f:
        cards = json.load(f)

    relevant = [c for c in cards
                if c.get("set") not in EXCLUDED_SETS and c.get("type") in TYPES and c.get("text")]

    texts = {}
    for c in relevant:
        if c.get("collectible"):
            continue
        text = normalize(c.get("text"))
        if GENERATOR.search(text):
            texts[c["id"]] = text

    by_name = {}
    for c in cards:
        if c.get("collectible") and c.get("set") not in EXCLUDED_SETS:
            by_name.setdefault(c.get("name"), []).append(c["id"])

    overrides = {}
    for pattern, action in OVERRIDES:
        rx = re.compile(pattern)
        for c in relevant:
            if c["id"] in overrides or not rx.search(normalize(c.get("text"))):
                continue
            kind, value = action[0], action[1]
            if kind == "cards":
                ids = sorted(i for name in value for i in by_name.get(name, []))
                if not ids:
                    raise SystemExit(f"override {pattern!r}: no collectible card named {value}")
                overrides[c["id"]] = f"new(CardIds: [{', '.join(cs(i) for i in ids)}])"
            elif kind == "text":
                overrides[c["id"]] = f"new(Text: {cs(value)})"
            elif kind == "sub":
                overrides[c["id"]] = f"new(Text: {cs(re.sub(value, action[2], normalize(c.get('text'))))})"
            else:
                overrides[c["id"]] = f"new(Skip: {cs(value)})"

    out = [HEADER]
    out.append("    /// <summary>Sets in Standard (fallback catalog only; the API lists formats per card).</summary>\n")
    out.append("    public static readonly IReadOnlySet<string> StandardSets = new HashSet<string>(StringComparer.Ordinal)\n    {\n")
    out.append("".join(f"        {cs(s)},\n" for s in STANDARD_SETS))
    out.append("    };\n\n")
    out.append("    /// <summary>Exception table: card id -> how to read its pool instead of its text.</summary>\n")
    out.append("    public static readonly IReadOnlyDictionary<string, PoolOverride> Overrides = new Dictionary<string, PoolOverride>(StringComparer.Ordinal)\n    {\n")
    out.append("".join(f"        [{cs(k)}] = {v},\n" for k, v in sorted(overrides.items())))
    out.append("    };\n\n")
    out.append("    /// <summary>English text of non-collectible generators (hero powers, tokens...).</summary>\n")
    out.append("    public static readonly IReadOnlyDictionary<string, string> GeneratorTexts = new Dictionary<string, string>(StringComparer.Ordinal)\n    {\n")
    out.append("".join(f"        [{cs(k)}] = {cs(v)},\n" for k, v in sorted(texts.items())))
    out.append("    };\n}\n")

    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print(f"{len(texts)} generator texts, {len(overrides)} overrides -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
